#!/bin/bash
# rt-effects-check.sh — verify the RT path with clang's function-effects
# analysis (see docs/dev/RT_HARDENING_CHECKLIST.md §2.1).
#
# Compiles the RT translation units with -Wfunction-effects (treated as an
# error) using the pinned clang provided by scripts/rt-clang.sh:
#
#   1. the core RTAPI/HAL library TUs (thread creation, funct dispatch),
#   2. every C translation unit of a compiled-in Go module — the halscope RT
#      sampler and the cyclic functions Go modules export through pkg/hal
#      (coverage is enforced by glob, not curated: see section 2b),
#   3. motmod — the motion controller (servo cycle + command handler),
#   4. tpmod + homemod (+cia402) — trajectory planner and homing,
#   5. lcec — the EtherCAT driver (masters, slaves, all device drivers),
#   6. hostmot2 — the Mesa FPGA driver (core, modules, eth/pci/epp transports),
#   7. every .comp component, freshly generated by modcompile (their functs
#      are typed STMAK_NONBLOCKING by the generator).
#
# Anything RTAPI_NONBLOCKING/STMAK_NONBLOCKING is verified transitively:
# allocation, locking, blocking calls, and static locals in the RT path
# are diagnosed.  Trust boundaries (RTAPI_NONBLOCKING_TRUSTED_*) are
# deliberate, justified exemptions — grep for them to audit.
#
# Usage: scripts/rt-effects-check.sh   (from the top-level directory,
# after a build: needs bin/modcompile and the generated GMI headers).
#
# Copyright (C) 2026 Sascha Ittner <sascha.ittner@modusoft.de>
# License: GPL Version 2

set -eu

TOP="$(cd "$(dirname "$0")/.." && pwd)"
cd "$TOP"

CLANG="$("$TOP/scripts/rt-clang.sh")"
echo "rt-effects-check: using $CLANG"

if [ ! -x "$TOP/bin/modcompile" ]; then
    echo "rt-effects-check: bin/modcompile not found — run make first" >&2
    exit 1
fi

CFLAGS_COMMON="-std=gnu11 -fsyntax-only -Wfunction-effects -Werror=function-effects"

fail=0
checked=0
skipped=0

# Scratch root for generated comps and per-TU depfiles (merged at the end).
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
DEPDIR="$SCRATCH/deps"
mkdir -p "$DEPDIR"

check_tu() {
    # check_tu <file> <extra include flags...>
    local tu="$1"; shift
    checked=$((checked+1))
    # -MMD records exactly which headers this TU includes (works under
    # -fsyntax-only).  The staleness guard at the end reads these to check the
    # generated GMI headers against their IDLs — the set is discovered by the
    # compiler, never a hand-kept list.
    if ! "$CLANG" $CFLAGS_COMMON -MMD -MF "$DEPDIR/dep-$checked.d" \
            -MT rt-effects-check "$@" "$tu"; then
        echo "rt-effects-check: FAILED: $tu" >&2
        fail=1
    fi
}

# --- 1. Core RTAPI/HAL library ---------------------------------------------

CORE_INC="-Isrc/hal -Isrc -Isrc/rtapi -Iinclude"
check_tu src/stmak/internal/hallib/uspace_rtapi_lib.c   $CORE_INC
check_tu src/stmak/internal/hallib/uspace_rtapi_string.c $CORE_INC
check_tu src/stmak/internal/hallib/hal_lib.c            $CORE_INC

# --- 2b. Go modules — the C translation units of compiled-in Go modules -----
# A Go module that needs one cyclic function contains a C function and exports
# it through pkg/hal (docs/dev/GOMOD_RT_DESIGN.md).  That function has to live
# in a real .c file precisely so this can compile it: a cgo preamble is built
# by cgo's own invocation and no checker ever sees it.
#
# Coverage is enforced, not curated.  EVERY .c file under src/stmak is
# discovered by glob and looked up below; one that is neither checked nor
# explicitly excluded fails the run.  A new RT file therefore cannot join the
# tree without either being verified or being argued about in this function —
# which is the point, since a checker that quietly stops covering the newest RT
# code is worse than no checker at all.
#
# Echo the include flags for a checked TU; echo nothing and return 1 for one
# that is deliberately out of scope (with the reason on stderr).

gomod_tu_includes() {
    case "$1" in
    # --- checked ---
    src/stmak/internal/halscope/halscope_rt.c)
        echo "$CORE_INC -Isrc/stmak/generated/gmi/halscope -Isrc/stmak/pkg/cmodule" ;;
    src/stmak/internal/hallib/rtfuncttest/rtfuncttest_rt.c)
        echo "$CORE_INC -Isrc/stmak/pkg/cmodule" ;;
    src/stmak/internal/pnptask/pnp_deadzone_rt.c)
        echo "$CORE_INC -Isrc/stmak/pkg/cmodule -Isrc/stmak/generated/gmi/mot" ;;
    # classicladder's scan function is compiled under the regime but claims
    # nothing yet: classicladder_refresh carries no STMAK_NONBLOCKING, so the
    # analysis has nothing to verify.  It is listed here rather than excluded
    # so that annotating it is a one-line change with the gate already in
    # place — and so the file cannot drift out of the build's reach.
    src/stmak/internal/classicladder/classicladder_rt.c)
        echo "$CORE_INC" ;;

    # --- deliberately out of scope (reason on stdout, exit 1) ---
    # Already covered above as the core RTAPI/HAL library (section 1).
    src/stmak/internal/hallib/hal_lib.c|\
    src/stmak/internal/hallib/uspace_rtapi_lib.c|\
    src/stmak/internal/hallib/uspace_rtapi_string.c)
        echo "checked above as the core RTAPI/HAL library"; return 1 ;;
    # C unit-test harnesses and non-RT support code: never on a HAL thread.
    src/stmak/internal/halscope/testrt/test_halscope_rt.c)
        echo "C unit-test harness, built against a mock rtapi"; return 1 ;;
    src/stmak/internal/classicladder/testdata/oracle/oracle_main.c)
        echo "standalone oracle that generates test fixtures"; return 1 ;;
    src/stmak/internal/task/interp_param_io_persist.c)
        echo "interpreter parameter I/O, userspace only"; return 1 ;;
    src/stmak/internal/tptest/tp_sources.c)
        echo "amalgamation unit for the tp test harness"; return 1 ;;

    *) return 2 ;;
    esac
}

for tu in $(find src/stmak -name '*.c' | sort); do
    ans="$(gomod_tu_includes "$tu")" && rc=0 || rc=$?
    case "$rc" in
    0)  check_tu "$tu" $ans ;;
    1)  echo "rt-effects-check: skipping $tu ($ans)"
        skipped=$((skipped+1)) ;;
    *)  echo "rt-effects-check: ERROR: unclassified C file under src/stmak: $tu" >&2
        echo "rt-effects-check: add it to gomod_tu_includes() in $0 — either with" >&2
        echo "rt-effects-check: its include flags, or with the reason it is not RT" >&2
        fail=1 ;;
    esac
done

# --- 3. motmod — the motion controller cmod --------------------------------
# Same defines/includes as the motmod.so rule in src/cnc/motion/Submakefile.

MOTMOD_INC="-DUSPACE -D_GNU_SOURCE -Drealtime -DSEQUENTIAL_SUPPORT \
    -DMOTMOD_INTERNAL \
    -fno-builtin-sin -fno-builtin-cos -fno-builtin-sincos \
    -fno-strict-aliasing -fwrapv \
    -Isrc -Iinclude -Isrc/rtapi -Isrc/stmak/pkg/cmodule \
    -Isrc/stmak/generated/gmi/kins -Isrc/stmak/generated/gmi/tp \
    -Isrc/stmak/generated/gmi/home -Isrc/stmak/generated/gmi/mot \
    -Isrc/stmak/generated/gmi/motctl -Isrc/stmak/generated/gmi/motstat \
    -Isrc/cnc/tp -Isrc/cnc/motion"

for tu in src/cnc/motion/motion.c src/cnc/motion/command.c \
          src/cnc/motion/control.c src/cnc/motion/axis.c \
          src/cnc/motion/simple_tp.c src/cnc/motion/motctl_handlers.c \
          src/cnc/motion/motstat_handlers.c src/cnc/kinematics/cubic.c; do
    check_tu "$tu" $MOTMOD_INC
done

# --- 4. tpmod + homemod — trajectory planner and homing cmods --------------
# Same defines/includes as their rules in src/Makefile.  posemath is
# in-scope (annotated + verified, not trusted).  -fno-builtin-sin/-cos
# from the production rule is intentionally NOT passed: it would make
# libm sin/cos non-builtin and thus non-inferrable for the analysis.

TPMOD_INC="-DUSPACE -D_GNU_SOURCE -Drealtime \
    -fno-strict-aliasing -fwrapv \
    -Isrc -Isrc/posemath -Isrc/cnc/nml_intf -Iinclude \
    -Isrc/stmak/pkg/cmodule -Isrc/stmak/generated/gmi/tp \
    -Isrc/stmak/generated/gmi/mot -Isrc/cnc/motion -Isrc/cnc/tp"

for tu in src/cnc/tp/tp.c src/cnc/tp/tc.c src/cnc/tp/tcq.c \
          src/cnc/tp/spherical_arc.c src/cnc/tp/blendmath.c \
          src/cnc/nml_intf/emcpose.c src/posemath/_posemath.c; do
    check_tu "$tu" $TPMOD_INC
done

HOMEMOD_INC="-DUSPACE -D_GNU_SOURCE -Drealtime \
    -fno-strict-aliasing -fwrapv \
    -Isrc -Iinclude -Isrc/stmak/pkg/cmodule \
    -Isrc/stmak/generated/gmi/home -Isrc/stmak/generated/gmi/mot \
    -Isrc/cnc/motion"

for tu in src/cnc/motion/homing.c src/cnc/motion/homemod_cia402.c; do
    check_tu "$tu" $HOMEMOD_INC
done

# --- 5. lcec — the EtherCAT master driver ----------------------------------
# Same defines/includes as the ethercat.so rule.  The EtherLab master
# library now natively annotates its documented rt_safe subset with
# ECRT_RT_ATTR (master include/ecrt.h); lcec.h hands that over to
# STMAK_NONBLOCKING (#define ECRT_RT_ATTR before #include "ecrt.h"), so the
# lcec RT code below verifies against the library's own annotations and a
# non-RT ecrt call (SDO/EoE/config) from RT context is a diagnosable
# error.  The master IMPLEMENTATION is verified separately in section 8.

LCEC_INC="-DULAPI -URTAPI \
    -Isrc/hal/drivers/ethercat -Isrc -Iinclude \
    -Isrc/stmak/generated/gmi/ethercat -Isrc/stmak/pkg/cmodule"

for tu in src/hal/drivers/ethercat/main.c src/hal/drivers/ethercat/master.c \
          src/hal/drivers/ethercat/slave.c src/hal/drivers/ethercat/util.c \
          src/hal/drivers/ethercat/dcsync_r2m.c src/hal/drivers/ethercat/dcsync_m2r.c \
          src/hal/drivers/ethercat/typelist.c \
          src/hal/drivers/ethercat/classes/class_enc.c \
          src/hal/drivers/ethercat/classes/class_ax5.c \
          src/hal/drivers/ethercat/devices/*.c; do
    check_tu "$tu" $LCEC_INC
done

# --- 6. hostmot2 — Mesa FPGA driver core + transports -----------------------
# Same defines/includes as the rules in the mesa-hostmot2 Submakefile.
# Every .c in the driver directory is checked (glob, so new TUs cannot
# silently escape the gate).  The board register exchange of the eth and
# spi/spix transports (raw LBP16 from the servo thread over UDP or spidev)
# is those transports' documented architecture — trusted at the
# eth_socket_send/recv, spi_ioc_message and spidev_ioc_message seams.

HM2_INC="-DUSPACE -D_GNU_SOURCE -Drealtime \
    -fno-strict-aliasing -fwrapv \
    -Isrc/rtapi/pci -Isrc/rtapi/parport -Isrc -Iinclude \
    -Isrc/hal/drivers/mesa-hostmot2 -Isrc/stmak/pkg/cmodule \
    -Isrc/stmak/generated/gmi/hm2_llio -Isrc/stmak/generated/gmi/hm2_serial"

for tu in src/hal/drivers/mesa-hostmot2/*.c; do
    check_tu "$tu" $HM2_INC
done

# --- 7. All .comp components (generated by modcompile) ---------------------

COMP_INC="-Isrc/stmak/pkg/cmodule \
    -Isrc/stmak/generated/gmi/kins \
    -Isrc/stmak/generated/gmi/home \
    -Isrc/stmak/generated/gmi/mot \
    -Isrc/stmak/generated/gmi/manualtoolchange \
    -Isrc/stmak/generated/gmi/hm2_serial"

GEN_DIR="$SCRATCH/gen"
mkdir -p "$GEN_DIR"

for comp in src/hal/components/*.comp src/hal/drivers/*.comp; do
    name="$(basename "$comp" .comp)"
    gen="$GEN_DIR/$name.c"
    # Comps that modcompile cannot generate (unsupported legacy features)
    # are skipped — they are not part of the stratuMAK build either.
    if ! ./bin/modcompile --preprocess "$comp" > "$gen" 2>/dev/null; then
        echo "rt-effects-check: skipping $name (modcompile cannot generate it)"
        skipped=$((skipped+1))
        continue
    fi
    check_tu "$gen" $COMP_INC
done

# --- 8. EtherLab master library — its own RT implementation audit ----------
# The master is no longer a trust boundary.  It natively annotates its
# documented rt_safe subset (ECRT_RT_ATTR) and ships a transitive
# function-effects check of its cyclic IMPLEMENTATION — master
# send/receive/domain, the userspace device layer and the raw/ccat
# transports — with rt_ok/rt_bad/rt_override self-tests for the contract
# itself.  Running it here means one target verifies the whole EtherCAT RT
# path: the lcec driver (section 5) AND the master it calls into.  The
# submodule uses the same pinned clang; hand it over via RT_CLANG so it is
# resolved once.

ECMASTER_CHECK="src/hal/drivers/ethercat/master/script/rt-effects-check.sh"
if [ -x "$ECMASTER_CHECK" ]; then
    echo "rt-effects-check: --- EtherLab master library (transitive impl audit) ---"
    if RT_CLANG="$CLANG" "$ECMASTER_CHECK"; then
        checked=$((checked+1))
    else
        echo "rt-effects-check: FAILED: EtherLab master library" >&2
        fail=1
    fi
else
    echo "rt-effects-check: skipping EtherLab master (submodule check absent)"
    skipped=$((skipped+1))
fi

# Read-only staleness guard.  The per-TU depfiles name exactly the generated GMI
# headers the RT TUs #include (discovered by the compiler, not a hand list).  If
# any is older than its IDL, a full build has not regenerated it — a pull or
# branch switch left it stale — and the check above just compiled against a
# stale header, so its verdict is unreliable.  Report that instead of a silent
# pass.  This only READS mtimes: it never writes to or regenerates the tree, so
# it cannot perturb a subsequent make.  Header stmak/generated/gmi/<api>/... maps
# to IDL gmi/idl/<api>.gmi by directory name.
stale=""
for h in $(cat "$DEPDIR"/*.d 2>/dev/null \
        | grep -oE 'src/stmak/generated/gmi/[A-Za-z0-9_]+/[A-Za-z0-9_]+_api\.h' \
        | sort -u); do
    api="$(basename "$(dirname "$h")")"
    idl="src/gmi/idl/$api.gmi"
    if [ -f "$idl" ] && [ "$idl" -nt "$h" ]; then
        case " $stale " in *" $api "*) ;; *) stale="$stale $api" ;; esac
    fi
done
if [ -n "$stale" ]; then
    echo "rt-effects-check: ERROR: stale generated GMI header(s):$stale" >&2
    echo "rt-effects-check: their IDL is newer — run 'make' first, then re-run" >&2
    fail=1
fi

if [ "$fail" -ne 0 ]; then
    echo "rt-effects-check: FAILED ($checked TUs checked)" >&2
    exit 1
fi
echo "rt-effects-check: OK — $checked TUs verified, $skipped skipped"
